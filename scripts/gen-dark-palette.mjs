// Generates app/dark-palette.css — dark-mode equivalents for colored utility classes.
// Run: node scripts/gen-dark-palette.mjs   (commit the output)
//
// Neutrals flip through CSS variables in globals.css. Colored ramps can't be flipped
// that way: one variable feeds both `bg-green-700` (a solid button that must stay
// dark green) and `text-green-700` (text that must get lighter on a dark surface).
// So each role gets its own rule:
//   light tints as backgrounds/borders -> translucent tints of the 500 shade
//   dark shades as text               -> the lighter end of the same ramp
// Anything inside `.keep-colors` (e.g. a white button on a photo) is left alone.
import { writeFileSync } from 'node:fs'

const RAMPS = {
  green: 'full', emerald: 'full', lime: 'full', teal: 'full', cyan: 'full', sky: 'full',
  blue: 'full', indigo: 'full', violet: 'full', purple: 'full', pink: 'full', rose: 'full',
  red: 'full', orange: 'full', amber: 'full', yellow: 'full',
  brass: 'brass', // custom ramp 50–700 (globals.css)
}
const BG = { 50: 10, 100: 16, 200: 24 }            // % of the 500 shade over the surface
const HOVER_BG = { 50: 14, 100: 20 }
const BORDER = { 100: 20, 200: 28, 300: 40 }
const TEXT = { 600: 400, 700: 400, 800: 300, 900: 200 } // dark shade -> light shade
const BRASS_TEXT = { 500: 300, 600: 300, 700: 300 }

const not = ':not(.keep-colors, .keep-colors *)'
const esc = (s) => s.replace(':', '\\:')
const mix = (c, pct) => `color-mix(in oklab, var(--color-${c}-500) ${pct}%, transparent)`
const out = []
for (const [c, kind] of Object.entries(RAMPS)) {
  out.push(`/* ${c} */`)
  for (const [shade, pct] of Object.entries(BG)) out.push(`.dark .bg-${c}-${shade}${not} { background-color: ${mix(c, pct)}; }`)
  for (const [shade, pct] of Object.entries(HOVER_BG)) out.push(`.dark .${esc(`hover:bg-${c}-${shade}`)}${not}:hover { background-color: ${mix(c, pct)}; }`)
  for (const [shade, pct] of Object.entries(BORDER)) out.push(`.dark .border-${c}-${shade}${not} { border-color: ${mix(c, pct)}; }`)
  for (const [shade, to] of Object.entries(kind === 'brass' ? BRASS_TEXT : TEXT)) out.push(`.dark .text-${c}-${shade}${not} { color: var(--color-${c}-${to}); }`)
}
// The pin-flag red only has 400–600: lift its text to 400 on dark surfaces.
out.push('/* flag */', `.dark :is(.text-flag-500, .text-flag-600)${not} { color: var(--color-flag-400); }`)

writeFileSync(new URL('../app/dark-palette.css', import.meta.url), `/* GENERATED by scripts/gen-dark-palette.mjs — do not edit by hand. */\n${out.join('\n')}\n`)
console.log(`wrote ${out.length} rules`)
